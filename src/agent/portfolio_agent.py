"""
Portfolio Analytics Agent.

Architecture
------------
The agent uses Gemini's native function-calling (tool-use) feature.
Every user turn goes through a two-step cycle:

  Step 1 — Intent dispatch (mode=AUTO, 2 tools)
    The question is sent to Gemini with TWO tool declarations:
      - run_sql_query(sql)              — database questions
      - calculate_exposure(portfolio_name) — sector exposure questions

    With mode=AUTO, Gemini may either call a tool (for portfolio questions)
    or return plain text (for off-topic questions).  This gives Gemini a
    binary tool choice for portfolio questions — no escape hatch — while
    still allowing it to refuse off-topic questions naturally.

  Step 2 — Execute & synthesise
    - run_sql_query / calculate_exposure: execute tool, send result back to
      Gemini (without tools) for natural-language synthesis.
    - No tool call (plain text): return the text directly, no DB access.

Why not mode=ANY with a decline_question tool?
------------------------------------------------
An earlier version used mode=ANY with three tools including decline_question.
This forced a 3-way classification on every turn.  For complex portfolio
questions that partially overlapped with multiple tools (e.g. questions
mentioning "sectors" but requiring SQL, not exposure calculation), Gemini
defaulted to decline_question as the safest choice.  Reducing to 2 tools
with mode=AUTO eliminates the ambiguity.

SQL safety
----------
All SQL generated by Gemini is validated (SELECT-only, no DDL/DML) before
execution. The validation layer in sql_tool.py is the last line of defence.
"""

