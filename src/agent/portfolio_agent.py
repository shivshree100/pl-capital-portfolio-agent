# With mode=AUTO, Gemini can either call a tool (for portfolio questions)
# or return plain text (for off-topic questions).  This eliminates the 3-way
# classification ambiguity that caused valid portfolio questions to be declined.
_TOOL_CONFIG = types.ToolConfig(
    function_calling_config=types.FunctionCallingConfig(mode="AUTO"),
)

# Forced mode: used as a RETRY when mode=AUTO returns no tool call for a
# question that appears to be about portfolio data.  mode=ANY guarantees
# the model calls one of the two tools, eliminating the "I'll just return
# text" escape for valid portfolio questions.
_FORCED_TOOL_CONFIG = types.ToolConfig(
    function_calling_config=types.FunctionCallingConfig(mode="ANY"),
)

# Keywords that indicate a question is likely about portfolio data.
# If the first dispatch (mode=AUTO) returns no tool call but the question
# contains any of these, we retry with mode=ANY to force a tool call.
_PORTFOLIO_KEYWORDS = [
    "portfolio", "portfolios", "holdings", "holding", "sector", "sectors",
    "securities", "security", "fund", "funds", "aum", "risk", "benchmark",
    "benchmarks", "transaction", "transactions", "performance", "price",
    "prices", "exposure", "diversification", "equity", "stock", "stocks",
    "bond", "bonds", "nav", "sharpe", "volatility", "drawdown", "return",
    "allocation", "weight", "cost basis", "market value", "active",
    "passive", "technology", "financials", "healthcare", "energy",
    "consumer", "automotive", "industrials", "utilities", "real estate",
]


def _looks_like_portfolio_question(question: str) -> bool:
    """Check if a question contains portfolio-related keywords."""
    q_lower = question.lower()
    return any(kw in q_lower for kw in _PORTFOLIO_KEYWORDS)


# ---------------------------------------------------------------------------
# Agent
# ---------------------------------------------------------------------------

class PortfolioAgent:
    """
    AI-powered portfolio analytics agent.

    Parameters
    ----------
    api_key : str, optional
        Gemini API key. If omitted, loaded from GEMINI_API_KEY in .env.
    model : str, optional
        Gemini model name. Defaults to DEFAULT_MODEL.
    db_path : Path, optional
        Database path override for testing.
    """

    DEFAULT_MODEL = "gemini-3.8-flash"
    _FALLBACK_MODELS = [
        "gemini-3.5-flash",
        "gemini-3.8-flash",
        "gemini-3.7-flash",
        "gemini-3.6-flash",
    ]

    def __init__(
        self,
        api_key: Optional[str] = None,
        model: Optional[str] = None,
        db_path: Optional[Path] = None,
    ) -> None:
        load_dotenv(get_project_root() / ".env")
        resolved_key = api_key or os.environ.get("GEMINI_API_KEY", "")
        if not resolved_key:
            raise RuntimeError(
                "GEMINI_API_KEY is not set.\n"
                "Create a .env file in the project root:\n"
                "  GEMINI_API_KEY=your_key_here\n"
                "Get a free key at https://ai.google.dev/gemini-api/docs"
            )

        self._client = genai.Client(
            api_key=resolved_key,
            http_options=types.HttpOptions(timeout=120000),
        )
        self._model = model or self.DEFAULT_MODEL
        self._db_path = db_path

    # ------------------------------------------------------------------
    # Public interface
    # ------------------------------------------------------------------

    def answer(self, question: str) -> str:
        """
        Answer a natural-language question about portfolio data.

        Always returns a string. Never raises for business-logic failures.
        Raises RuntimeError only for unrecoverable API/infrastructure errors
        during the dispatch step.  If the synthesis step fails (API overload),
        the raw tool result is returned as a fallback so the user still gets
        useful data.
        """
        if not question or not question.strip():
            return "Please enter a question."

        # Check response cache before hitting Gemini
        try:
            from src.cache import query_cache, _NOT_FOUND
            cache_key = f"agent:answer:{question.strip().lower()}"
            cached_answer = query_cache.get(cache_key)
            if cached_answer is not _NOT_FOUND:
                return cached_answer
        except Exception:
            cache_key = None

        # Step 1: Gemini picks a tool or returns plain text (mode=AUTO)
        response = self._call_gemini_dispatch(question)
        tool_call = self._extract_tool_call(response)

        # Step 1b: if no tool call but the question looks like portfolio data,
        # retry with mode=ANY to force a tool call.  This catches the case
        # where the model is uncertain and returns text instead of calling
        # a tool for a valid portfolio question.
        if tool_call is None and _looks_like_portfolio_question(question):
            response = self._call_gemini_dispatch_forced(question)
            tool_call = self._extract_tool_call(response)

        # Step 2a: no tool call — Gemini returned plain text (off-topic question
        # or malformed response)
        if tool_call is None:
            text = self._extract_text(response)
            if text and text != "(No response received)":
                return text
            return (
                "I could not process your request. "
                "The model returned an unexpected response."
            )

        # Step 2b: execute the chosen tool
        tool_name, tool_args = tool_call
        tool_result = self._dispatch_tool(tool_name, tool_args)

        # Step 3: send tool result back to Gemini for natural-language synthesis.
        # If the synthesis API call fails (e.g. all models overloaded), fall
        # back to returning the raw tool result so the user still gets data.
        try:
            final_response = self._call_gemini_synthesise(
                question, response, tool_name, tool_result
            )
            answer_text = self._extract_text(final_response)
            if answer_text and answer_text != "(No response received)":
                # Cache successful answers (120s TTL via query_cache)
                try:
                    from src.cache import query_cache
                    if cache_key:
                        query_cache.set(cache_key, answer_text)
                except Exception:
                    pass
                return answer_text
            # Synthesis returned empty — fall through to raw tool result
            print("  [WARN] Synthesis returned no text; showing raw tool result.")
        except RuntimeError as exc:
            print(f"  [WARN] Synthesis failed: {exc}")
            print("  [WARN] Showing raw tool result as fallback.")

        return tool_result

    # ------------------------------------------------------------------
    # Public interface — evaluation dispatch (no synthesis API call)
    # ------------------------------------------------------------------

    def dispatch(self, question: str) -> tuple[str, dict, SqlResult | ExposureResult | None]:
        """
        Run dispatch + tool execution without NL synthesis.

        Sends the question to Gemini, extracts the tool call, and executes
        the selected tool.  Returns the raw structured result (SqlResult or
        ExposureResult), not a formatted string.  Does NOT call the
        synthesis API — designed for evaluation, not end-user display.

        Parameters
        ----------
        question : str
            A natural-language question.

        Returns
        -------
        tuple of (tool_name, tool_args, tool_result)
            tool_name   : str — "run_sql_query", "calculate_exposure",
                          or "decline_question"
            tool_args   : dict — the arguments Gemini chose for the tool
            tool_result : SqlResult | ExposureResult | None — the raw
                          structured result from executing the tool.
                          None when the tool is decline_question.

        Raises
        ------
        RuntimeError
            If the Gemini dispatch API call fails (all models unavailable).
        """
        response = self._call_gemini_dispatch(question)
        tool_call = self._extract_tool_call(response)

        # Retry with mode=ANY if no tool call but question looks like portfolio data
        if tool_call is None and _looks_like_portfolio_question(question):
            response = self._call_gemini_dispatch_forced(question)
            tool_call = self._extract_tool_call(response)

        if tool_call is None:
            # No tool call — model returned plain text (off-topic or error)
            return "decline_question", {}, None

        tool_name, tool_args = tool_call

        if tool_name == "run_sql_query":
            sql = tool_args.get("sql", "")
            result = execute_sql_query(sql, db_path=self._db_path)
            return tool_name, tool_args, result

        elif tool_name == "calculate_exposure":
            portfolio_name = tool_args.get("portfolio_name", "")
            result = calculate_sector_exposure(portfolio_name, db_path=self._db_path)
            return tool_name, tool_args, result

        else:
            # decline_question or unknown — no structured data result
            return tool_name, tool_args, None

    # ------------------------------------------------------------------
    # Step 1: dispatch call — tools=_TOOLS, mode=ANY
    # ------------------------------------------------------------------

    def _call_gemini_dispatch(
        self, question: str
    ) -> types.GenerateContentResponse:
        """
        Send the user question to Gemini with mode=AUTO.
        RAG context (verified database facts) is prepended to the question
        when relevant entities are detected.
        The model may call a tool or return plain text.
        """
        # Build RAG context — inject verified facts for detected entities
        try:
            from src.rag import build_context
            context = build_context(question, db_path=self._db_path)
        except Exception:
            context = ""  # degrade gracefully if RAG fails

        # Prepend context to the question if we have any
        augmented = (
            f"{context}\n\n## User Question\n{question}"
            if context
            else question
        )

        config = types.GenerateContentConfig(
            system_instruction=_SYSTEM_PROMPT,
            temperature=0.0,
            max_output_tokens=512,
            tools=_TOOLS,
            tool_config=_TOOL_CONFIG,
        )
        return self._call_with_fallback(augmented, config, step="dispatch")

    def _call_gemini_dispatch_forced(
        self, question: str
    ) -> types.GenerateContentResponse:
        """
        Retry dispatch with mode=ANY — forces the model to call one of
        the two tools.  Used when mode=AUTO returned no tool call for a
        question that appears to be about portfolio data.
        """
        config = types.GenerateContentConfig(
            system_instruction=_SYSTEM_PROMPT,
            temperature=0.0,
            max_output_tokens=512,
            tools=_TOOLS,
            tool_config=_FORCED_TOOL_CONFIG,
        )
        return self._call_with_fallback(question, config, step="dispatch-forced")

    # ------------------------------------------------------------------
    # Step 3: synthesis call — no tools, plain text response
    # ------------------------------------------------------------------

    def _call_gemini_synthesise(
        self,
        original_question: str,
        dispatch_response: types.GenerateContentResponse,
        tool_name: str,
        tool_result: str,
    ) -> types.GenerateContentResponse:
        """
        Send the tool result back to Gemini so it can write the final answer.

        No tools are passed here — we want a plain text response.
        The conversation history is: user → model (function_call) → user (function_response).
        """
        # Extract the model's function_call part to reconstruct the turn
        fc_part = None
        try:
            for cand in dispatch_response.candidates or []:
                for part in cand.content.parts or []:
                    if part.function_call is not None:
                        fc_part = part
                        break
                if fc_part:
                    break
        except (AttributeError, TypeError):
            pass

        contents = [
            types.Content(role="user", parts=[types.Part(text=original_question)]),
        ]
        if fc_part is not None:
            contents.append(
                types.Content(role="model", parts=[fc_part])
            )
        contents.append(
            types.Content(
                role="user",
                parts=[
                    types.Part(
                        function_response=types.FunctionResponse(
                            name=tool_name,
                            response={"result": tool_result},
                        )
                    )
                ],
            )
        )

        config = types.GenerateContentConfig(
            system_instruction=_SYNTHESIS_PROMPT,
            temperature=0.0,
            max_output_tokens=2048,
            # No tools — we want Gemini to write text, not call another tool
        )
        return self._call_with_fallback(contents, config, step="synthesise")

    # ------------------------------------------------------------------
    # Shared API caller with fallback
    # ------------------------------------------------------------------

    def _call_with_fallback(
        self,
        contents,
        config: types.GenerateContentConfig,
        step: str,
    ) -> types.GenerateContentResponse:
        """
        Call generate_content, falling back through _FALLBACK_MODELS on 503.

        Each model is retried up to 2 times on 503 (with a 5-second delay)
        before moving to the next model.  This gives the primary model time
        to recover from temporary overload before switching to a different
        model that may have different function-calling behaviour.
        """
        models = list(dict.fromkeys([self._model] + self._FALLBACK_MODELS))
        last_exc: Exception = RuntimeError("No models attempted.")

        for model in models:
            for attempt in range(2):  # retry each model once on 503
                try:
                    response = self._client.models.generate_content(
                        model=model,
                        contents=contents,
                        config=config,
                    )
                    if model != self._model:
                        print(f"  [INFO] Fallback model used: {model}")
                    return response
                except genai_errors.ServerError as exc:
                    last_exc = exc
                    if attempt < 1:
                        print(f"  [WARN] {model} unavailable (503), retrying...")
                        time.sleep(5)
                    else:
                        print(f"  [WARN] {model} still unavailable, trying next model…")
                except genai_errors.ClientError as exc:
                    # 404 model not available for this key — skip immediately
                    last_exc = exc
                    break  # don't retry 404s
                except Exception as exc:
                    last_exc = exc
                    break

        raise RuntimeError(
            f"Gemini API error during {step}: {last_exc}"
        ) from last_exc

    # ------------------------------------------------------------------
    # Helper: extract function call from dispatch response
    # ------------------------------------------------------------------

    def _extract_tool_call(
        self, response: types.GenerateContentResponse
    ) -> Optional[tuple[str, dict]]:
        """
        Extract (tool_name, args_dict) from a dispatch response.

        With mode=AUTO, the model may return a function_call part (for
        portfolio questions) or plain text (for off-topic questions).
        Returns None when no function call is present.
        """
        try:
            for cand in response.candidates or []:
                for part in cand.content.parts or []:
                    if part.function_call is not None:
                        fc = part.function_call
                        return (fc.name, dict(fc.args))
        except (AttributeError, TypeError):
            pass

        # No function call found — model returned plain text
        return None

    # ------------------------------------------------------------------
    # Helper: extract text from synthesis response
    # ------------------------------------------------------------------

    def _extract_text(self, response: types.GenerateContentResponse) -> str:
        """
        Extract the text from a synthesis response (no tools — pure text).
        Never accesses response.text on a dispatch response.
        """
        try:
            text = response.text
            if text:
                return text
        except Exception:
            pass

        # Fallback: collect all text parts manually
        parts = []
        try:
            for cand in response.candidates or []:
                for part in cand.content.parts or []:
                    if getattr(part, "text", None):
                        parts.append(part.text)
        except (AttributeError, TypeError):
            pass

        return " ".join(parts) if parts else "(No response received)"

    # ------------------------------------------------------------------
    # Helper: execute the chosen tool
    # ------------------------------------------------------------------

    def _dispatch_tool(self, tool_name: str, args: dict) -> str:
        """
        Execute the named tool and return a formatted string result.
        SQL validation is always applied before execution.
        """
        if tool_name == "run_sql_query":
            sql = args.get("sql", "")

            err = validate_sql(sql)
            if err:
                return f"SQL validation failed: {err}\nAttempted SQL:\n{sql}"

            result = execute_sql_query(sql, db_path=self._db_path)
            if not result.success:
                return f"SQL execution failed: {result.error}\nSQL:\n{sql}"

            formatted = format_sql_result(result)
            truncation = " (capped at 500 rows)" if result.truncated else ""
            return (
                f"SQL executed successfully.\n"
                f"Rows returned: {result.row_count}{truncation}\n\n"
                f"Result:\n{formatted}"
            )

        elif tool_name == "calculate_exposure":
            portfolio_name = args.get("portfolio_name", "")
            result = calculate_sector_exposure(portfolio_name, db_path=self._db_path)
            formatted = format_exposure_result(result)
            display = result.to_display_dict()
            return (
                f"Sector exposure calculation completed.\n\n"
                f"{formatted}\n\n"
                f"Data: {display}"
            )

        else:
            return (
                f"Unknown tool '{tool_name}'. "
                "Available tools: run_sql_query, calculate_exposure, decline_question."
            )
